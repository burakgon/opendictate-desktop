//! The general pasteboard, used to paste text and to read the selection with ⌘C.
//!
//! Before OpenDictate borrows the clipboard it takes a snapshot of *every* item and type on it
//! (images, files, rich text, ...), and puts that back afterwards - unless something else wrote
//! to the clipboard in the meantime.

use objc2::{rc::Retained, runtime::ProtocolObject};
use objc2_app_kit::{NSPasteboard, NSPasteboardItem, NSPasteboardTypeString, NSPasteboardWriting};
use objc2_foundation::{NSArray, NSData, NSString};

/// Marker types from nspasteboard.org: clipboard managers (Maccy, Paste, Raycast, Alfred, ...)
/// don't record content flagged like this.
const TRANSIENT_TYPES: &[&str] = &["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];

/// Snapshots larger than this are not kept (a huge image would cost memory for little benefit).
const MAX_SNAPSHOT_BYTES: usize = 64 * 1024 * 1024;

fn general() -> Retained<NSPasteboard> {
    NSPasteboard::generalPasteboard()
}

/// Increments whenever anyone writes to the clipboard.
pub fn change_count() -> isize {
    general().changeCount()
}

pub fn get_text() -> Option<String> {
    // SAFETY: reading a string type from the pasteboard.
    general().stringForType(unsafe { NSPasteboardTypeString }).map(|s| s.to_string())
}

/// Replaces the clipboard with `text`. Transient text is hidden from clipboard managers.
/// Returns the clipboard's new change count.
pub fn set_text(text: &str, transient: bool) -> isize {
    let pb = general();
    pb.clearContents();
    let item = NSPasteboardItem::new();
    // SAFETY: NSPasteboardTypeString is a valid pasteboard type constant.
    item.setString_forType(&NSString::from_str(text), unsafe { NSPasteboardTypeString });
    if transient {
        let empty = NSData::new();
        for t in TRANSIENT_TYPES {
            item.setData_forType(&empty, &NSString::from_str(t));
        }
    }
    write_items(&pb, vec![item]);
    pb.changeCount()
}

fn write_items(pb: &NSPasteboard, items: Vec<Retained<NSPasteboardItem>>) {
    let objects: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> =
        items.into_iter().map(ProtocolObject::from_retained).collect();
    let array = NSArray::from_retained_slice(&objects);
    if !pb.writeObjects(&array) {
        log::warn!("could not write to the clipboard");
    }
}

/// Everything that was on the clipboard, item by item and type by type.
pub struct Snapshot {
    items: Vec<Vec<(Retained<NSString>, Retained<NSData>)>>,
}

pub fn snapshot() -> Snapshot {
    let mut items = Vec::new();
    let mut total = 0usize;
    if let Some(pb_items) = general().pasteboardItems() {
        for item in pb_items.iter() {
            let mut entries = Vec::new();
            for t in item.types().iter() {
                if let Some(data) = item.dataForType(&t) {
                    total += data.len();
                    entries.push((t, data));
                }
            }
            if !entries.is_empty() {
                items.push(entries);
            }
        }
    }
    if total > MAX_SNAPSHOT_BYTES {
        log::info!("clipboard holds {} MB; it won't be restored after pasting", total / (1024 * 1024));
        items.clear();
    }
    Snapshot { items }
}

/// Puts a snapshot back. An empty snapshot leaves the clipboard empty.
pub fn restore(snapshot: Snapshot) {
    let pb = general();
    pb.clearContents();
    if snapshot.items.is_empty() {
        return;
    }
    let items = snapshot
        .items
        .into_iter()
        .map(|entries| {
            let item = NSPasteboardItem::new();
            for (t, data) in entries {
                item.setData_forType(&data, &t);
            }
            item
        })
        .collect();
    write_items(&pb, items);
}
